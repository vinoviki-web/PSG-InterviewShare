#!/usr/bin/env node
/**
 * Generates supabase/seed-demo.sql from the prototype's FICTIONAL data
 * (src/mocks/seed.js) so database mode has realistic content to browse.
 * LOCAL DEVELOPMENT ONLY: never load this into staging or production.
 * Run: node scripts/gen-demo-seed.mjs
 */
import { registerHooks } from 'node:module'
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'

// src/mocks uses extensionless relative imports (Vite style); let Node resolve them.
registerHooks({
  resolve(spec, ctx, next) {
    try {
      return next(spec, ctx)
    } catch (e) {
      if (spec.startsWith('.') && !spec.endsWith('.js')) return next(`${spec}.js`, ctx)
      throw e
    }
  },
})
const { USERS, EXPERIENCES } = await import('../src/mocks/seed.js')

const uuid = (key) => {
  const h = createHash('md5').update(`roundwise-demo:${key}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`

// Mock ids → the fixed UUIDs of the accounts in seed.sql, else deterministic ones
const FIXED = { 'u-student': '11111111-1111-4111-8111-111111111111', 'u-mod': '22222222-2222-4222-8222-222222222222', 'u-admin': '33333333-3333-4333-8333-333333333333' }
const SEEDED_EMAILS = new Set(['22z201@psgtech.ac.in', '21z235@psgtech.ac.in', '22e646@psgtech.ac.in', '22z145@psgtech.ac.in'])
const takenHandles = new Set(['arjun-p', 'meera-k', 'admin', 'priya-r'])
const takenEmails = new Set(SEEDED_EMAILS)
const idFor = (mockId) => FIXED[mockId] ?? uuid(mockId)

const users = USERS.filter((u) => u.onboarded_at && !FIXED[u.id]).map((u, i) => {
  let email = u.email
  if (takenEmails.has(email)) email = email.replace('@', `x${i}@`)
  takenEmails.add(email)
  let handle = u.handle
  let n = 2
  while (takenHandles.has(handle)) handle = `${u.handle}-${n++}`
  takenHandles.add(handle)
  return { ...u, uuid: idFor(u.id), email, handle }
})

let sql = `-- =====================================================================
-- Roundwise · LOCAL DEMO CONTENT (generated by scripts/gen-demo-seed.mjs)
-- Fictional students and experiences from the prototype, for browsing in
-- database mode. NEVER load into staging or production.
-- =====================================================================

insert into auth.users (instance_id, id, aud, role, email, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token, reauthentication_token)
values
${users.map((u) => `  ('00000000-0000-0000-0000-000000000000', ${q(u.uuid)}, 'authenticated', 'authenticated', ${q(u.email)}, now(), '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: u.full_name }))}, ${q(u.created_at)}, ${q(u.created_at)}, '', '', '', '', '', '', '', '')`).join(',\n')};

insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
select gen_random_uuid(), u.id, u.id::text, jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true), 'email', now(), now(), now()
from auth.users u where u.id in (${users.map((u) => q(u.uuid)).join(', ')});

update public.profiles p set full_name = v.full_name, handle = v.handle, department_id = v.dept, graduation_year = v.yr,
  profile_visibility = v.vis::public.profile_visibility, onboarded_at = v.onboarded
from (values
${users.map((u) => `  (${q(u.uuid)}::uuid, ${q(u.full_name)}, ${q(u.handle)}, ${q(u.department_id)}, ${u.graduation_year}::smallint, ${q(u.profile_visibility)}, ${q(u.onboarded_at)}::timestamptz)`).join(',\n')}
) as v(id, full_name, handle, dept, yr, vis, onboarded)
where p.id = v.id;
`

const seenDrive = new Set()
const exps = EXPERIENCES.filter((e) => e.status === 'published' || e.status === 'hidden')
const rows = []
const rounds = []
const questions = []
const qtopics = []
const etopics = []
const resources = []
for (const e of exps) {
  const id = uuid(e.id)
  const author = idFor(e.author_id)
  const key = [author, e.company_slug, e.role_title.toLowerCase(), e.opportunity_type, e.graduation_year].join('|')
  const dupReason = seenDrive.has(key) ? 'Fictional demo data: another interview for the same drive' : null
  seenDrive.add(key)
  const anonymous = e.is_anonymous
  rows.push(
    `  (${q(id)}::uuid, ${q(author)}::uuid, ${q(e.company_slug)}, ${q(e.role_title)}, ${q(e.opportunity_type)}, ${q(e.hiring_mode)}, ${q(e.department_id)}, ${e.graduation_year}, ${q(e.interview_month)}::date, ` +
      `${e.eligibility ? `${q(JSON.stringify(e.eligibility))}::jsonb` : 'null'}, ${q(e.application_process)}, ${q(e.preparation)}, ${q(e.advice)}, ${e.difficulty}, ${q(e.outcome)}, ` +
      `${anonymous}, ${anonymous && e.hide_department}, ${q(e.status)}, ${q(e.hidden_reason ?? null)}, ${q(dupReason)}, ${q(e.published_at)}::timestamptz, ${e.view_count}, ${!!e.edited})`,
  )
  e.rounds.forEach((r) => {
    const rid = uuid(r.id)
    rounds.push(`  (${q(rid)}::uuid, ${q(id)}::uuid, ${r.position}, ${q(r.round_type)}, ${q(r.mode)}, ${r.duration_minutes ?? 'null'}, ${r.difficulty ?? 'null'}, ${q(r.description)})`)
    r.questions.forEach((qq) => {
      const qid = uuid(qq.id)
      questions.push(`  (${q(qid)}::uuid, ${q(id)}::uuid, ${q(rid)}::uuid, ${qq.position}, ${q(qq.body)}, ${q(qq.kind)})`)
      ;[...new Set(qq.topics)].slice(0, 5).forEach((t) => qtopics.push(`  (${q(qid)}::uuid, ${q(t)})`))
    })
  })
  ;[...new Set(e.topics)].slice(0, 15).forEach((t) => etopics.push(`  (${q(id)}::uuid, ${q(t)})`))
  e.resources.forEach((r, i) => resources.push(`  (${q(id)}::uuid, ${i + 1}, ${q(r.title)}, ${q(r.url)}, ${q(r.kind)})`))
}

sql += `
insert into public.experiences (id, author_id, company_id, role_title, opportunity_type, hiring_mode, department_id, graduation_year, interview_month,
  eligibility, application_process, preparation, advice, difficulty, outcome, is_anonymous, hide_department, status, hidden_reason, duplicate_reason,
  published_at, view_count, edited, confirmed_own, draft_step, draft_max_step)
select v.id, v.author, c.id, v.role, v.typ::public.opportunity_type, v.hiring::public.hiring_mode, v.dept, v.yr::smallint, v.month,
  v.el, v.app, v.prep, v.advice, v.diff::smallint, v.outcome::public.outcome, v.anon, v.hide_dept, v.status::public.experience_status, v.hidden_reason, v.dup,
  v.published, v.views, v.edited, true, 5, 5
from (values
${rows.join(',\n')}
) as v(id, author, company_slug, role, typ, hiring, dept, yr, month, el, app, prep, advice, diff, outcome, anon, hide_dept, status, hidden_reason, dup, published, views, edited)
join public.companies c on c.slug = v.company_slug;

insert into public.experience_rounds (id, experience_id, position, round_type, mode, duration_minutes, difficulty, description)
select v.id, v.eid, v.pos, v.typ::public.round_type, v.mode::public.round_mode, v.dur, v.diff, v.descr from (values
${rounds.join(',\n')}
) as v(id, eid, pos, typ, mode, dur, diff, descr);

insert into public.questions (id, experience_id, round_id, position, body, kind)
select v.id, v.eid, v.rid, v.pos, v.body, v.kind::public.question_kind from (values
${questions.join(',\n')}
) as v(id, eid, rid, pos, body, kind);

insert into public.question_topics (question_id, topic_id) values
${qtopics.join(',\n')}
on conflict do nothing;

insert into public.experience_topics (experience_id, topic_id) values
${etopics.join(',\n')}
on conflict do nothing;
`
if (resources.length) {
  sql += `
insert into public.experience_resources (experience_id, position, title, url, kind)
select v.eid, v.pos, v.title, v.url, v.kind::public.resource_kind from (values
${resources.join(',\n')}
) as v(eid, pos, title, url, kind);
`
}

// Real helpful votes (so "Most helpful" sorting is genuine): up to helpful_count voters, never the author
const voterPool = [...users.map((u) => u.uuid), FIXED['u-student'], FIXED['u-mod']]
const votes = []
exps.forEach((e, i) => {
  const author = idFor(e.author_id)
  const want = Math.min(e.helpful_count, 20)
  const pool = voterPool.filter((v) => v !== author)
  for (let k = 0; k < want && k < pool.length; k++) votes.push(`  (${q(pool[(i * 7 + k) % pool.length])}::uuid, ${q(uuid(e.id))}::uuid)`)
})
sql += `
insert into public.helpful_votes (user_id, experience_id) values
${votes.join(',\n')}
on conflict do nothing;

select public.refresh_experience_search(e.id) from public.experiences e;
`

writeFileSync(new URL('../supabase/seed-demo.sql', import.meta.url), sql)
console.log(`seed-demo.sql: ${users.length} students, ${rows.length} experiences, ${rounds.length} rounds, ${questions.length} questions, ${votes.length} helpful votes`)
